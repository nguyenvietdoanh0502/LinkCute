CREATE TABLE chat_groups (
    id UUID PRIMARY KEY,
    owner_id UUID NOT NULL REFERENCES users(id),
    name VARCHAR(100) NOT NULL CHECK (LENGTH(TRIM(name)) BETWEEN 1 AND 100),
    avatar_url TEXT,
    avatar_public_id VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE chat_group_participants (
    id UUID PRIMARY KEY,
    group_id UUID NOT NULL REFERENCES chat_groups(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id),
    invited_by_id UUID NOT NULL REFERENCES users(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('INVITED', 'MEMBER')),
    joined_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_group_participant UNIQUE (group_id, user_id),
    CONSTRAINT ck_group_joined CHECK ((status = 'INVITED' AND joined_at IS NULL) OR (status = 'MEMBER' AND joined_at IS NOT NULL))
);
CREATE INDEX idx_group_participant_user ON chat_group_participants(user_id, status);

CREATE TABLE chat_group_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id UUID NOT NULL REFERENCES chat_groups(id) ON DELETE CASCADE,
    sender_id UUID NOT NULL REFERENCES users(id),
    client_message_id UUID NOT NULL,
    content VARCHAR(2000) NOT NULL CHECK (LENGTH(TRIM(content)) BETWEEN 1 AND 2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_group_message_client UNIQUE (group_id, sender_id, client_message_id)
);
CREATE INDEX idx_group_message_history ON chat_group_messages(group_id, id DESC);
